package net.scarrix.hud;

import net.minecraft.client.gui.GuiGraphicsExtractor;

/** Original line icons; no third-party brand marks. */
final class IconPainter {
    static void line(GuiGraphicsExtractor g,int x,int y,int x2,int y2,int color) {
        int dx=Math.abs(x2-x),sx=x<x2?1:-1,dy=-Math.abs(y2-y),sy=y<y2?1:-1,err=dx+dy;
        while(true) { g.fill(x,y,x+1,y+1,color); if(x==x2 && y==y2) break; int e=2*err; if(e>=dy){err+=dy;x+=sx;} if(e<=dx){err+=dx;y+=sy;} }
    }
    static void draw(GuiGraphicsExtractor g,String name,int x,int y,int size,int color) {
        int[][] segments=switch(name) {
            case "shirt" -> new int[][]{{6,3,2,6},{2,6,5,10},{5,10,7,8},{7,8,7,18},{7,18,15,18},{15,18,15,8},{15,8,17,10},{17,10,20,6},{20,6,16,3},{6,3,9,6},{9,6,13,6},{13,6,16,3}};
            case "emote" -> new int[][]{{10,2,14,2},{14,2,14,6},{14,6,10,6},{10,6,10,2},{11,8,10,14},{10,14,7,20},{10,14,15,19},{11,8,5,5},{11,8,18,5}};
            case "friends" -> new int[][]{{5,3,9,3},{9,3,9,7},{9,7,5,7},{5,7,5,3},{2,17,2,12},{2,12,5,10},{5,10,9,10},{9,10,12,12},{12,12,12,17},{14,5,18,5},{18,5,18,9},{18,9,14,9},{14,9,14,5},{15,12,19,12},{19,12,21,15},{21,15,21,19}};
            case "compass" -> new int[][]{{11,1,20,11},{20,11,11,21},{11,21,2,11},{2,11,11,1},{8,15,11,7},{11,7,14,15},{14,15,8,15}};
            case "pin" -> new int[][]{{5,3,17,3},{17,3,19,10},{19,10,11,21},{11,21,3,10},{3,10,5,3},{8,7,14,7},{14,7,14,11},{14,11,8,11},{8,11,8,7}};
            case "keys" -> new int[][]{{7,2,15,2},{15,2,15,9},{15,9,7,9},{7,9,7,2},{1,11,21,11},{21,11,21,20},{21,20,1,20},{1,20,1,11},{7,11,7,20},{15,11,15,20}};
            case "back" -> new int[][]{{14,3,6,11},{6,11,14,19}};
            case "mods" -> new int[][]{{2,2,9,2},{9,2,9,9},{9,9,2,9},{2,9,2,2},{13,2,20,2},{20,2,20,9},{20,9,13,9},{13,9,13,2},{2,13,9,13},{9,13,9,20},{9,20,2,20},{2,20,2,13},{13,13,20,13},{20,13,20,20},{20,20,13,20},{13,20,13,13}};
            default -> new int[][]{{2,17,6,13},{6,13,10,15},{10,15,15,6},{15,6,21,3},{2,21,21,21},{2,21,2,2}};
        };
        for(int[] p:segments) line(g,x+p[0]*size/22,y+p[1]*size/22,x+p[2]*size/22,y+p[3]*size/22,color);
    }
}
